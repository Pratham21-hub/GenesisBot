"""Shared Pydantic domain models for GenesisBot V2.

These models define the internal contracts used across the agent architecture:
- SessionInfo: Tracks match/session metadata and lifecycle.
- GameState: Provisional internal representation of game state.
- ProposedAction: Internal candidate action generated by agent heuristics/strategy.
- LayaDecision: The synthesized strategy decision produced by the Laya decision engine.
- ActionSubmissionResult: Standardized outcome of dispatching an action to the game adapter.

Note on Schema Mapping:
Official competition schemas (API payloads, action wire-formats) will be finalized
upon competition kickoff. All internal models intentionally isolate raw payloads
and provide provisional internal abstractions that must be mapped to official
schemas via concrete adapters.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
import uuid

from pydantic import BaseModel, Field


def _utc_now() -> datetime:
    """Return timezone-aware current UTC datetime."""
    return datetime.now(timezone.utc)


class SessionInfo(BaseModel):
    """Session information and lifecycle tracking.

    Represents the active competition match, tournament bracket, or sandbox
    session in which GenesisBot is participating.
    """

    session_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for the active match or tournament session.",
    )
    bot_name: str = Field(
        default="GenesisBot",
        description="Bot name registered for this session.",
    )
    status: str = Field(
        default="initialized",
        description=(
            "Current session lifecycle state (e.g. 'initialized', 'active', "
            "'paused', 'completed', 'terminated'). Provisional internal abstraction."
        ),
    )
    created_at: datetime = Field(
        default_factory=_utc_now,
        description="UTC timestamp when the session record was created.",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Provisional key-value storage for competition-specific session attributes "
            "(e.g. room_id, opponent_id, arena_rules) to be mapped when official specs arrive."
        ),
    )


class GameState(BaseModel):
    """Provisional internal representation of the game state.

    This model serves as an internal abstraction decoupled from the actual competition
    wire schema. Upstream raw payloads from the competition server are preserved
    in `raw_state` to prevent data loss until the official schema is fully mapped.
    """

    turn_number: int = Field(
        default=0,
        ge=0,
        description="Monotonically increasing turn, round, or tick counter.",
    )
    is_active: bool = Field(
        default=True,
        description="Flag indicating whether the game is currently ongoing.",
    )
    score: Optional[float] = Field(
        default=None,
        description="Provisional internal score or performance metric, if available.",
    )
    time_remaining_ms: Optional[int] = Field(
        default=None,
        ge=0,
        description="Provisional millisecond allowance remaining for the current turn.",
    )
    raw_state: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Preserved raw upstream state payload received from the game server or SDK. "
            "Guarantees forward-compatibility before official schema mapping is written."
        ),
    )
    timestamp: datetime = Field(
        default_factory=_utc_now,
        description="UTC timestamp when this state observation was ingested.",
    )


class ProposedAction(BaseModel):
    """Provisional internal candidate action.

    Represents an action proposed by an agent strategy module. Concrete
    game adapters translate this internal action into the competition's
    wire format before dispatching to the game server.
    """

    action_type: str = Field(
        ...,
        description=(
            "Internal action identifier (e.g. 'move', 'interact', 'cast', 'idle'). "
            "Provisional internal abstraction to be mapped to the official action schema."
        ),
    )
    parameters: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Provisional dictionary of action parameters (e.g. coordinates, target_id, direction). "
            "Mapped to the official request body by the adapter."
        ),
    )
    priority: int = Field(
        default=1,
        ge=1,
        le=10,
        description="Internal evaluation priority rating (1 = lowest, 10 = critical override).",
    )
    reasoning: Optional[str] = Field(
        default=None,
        description="Human-readable rationale for this proposal, logged for explainability.",
    )


class LayaDecision(BaseModel):
    """The synthesized decision produced by the Laya decision engine.

    'Laya' represents GenesisBot's strategic cognitive agent. This model
    encapsulates the final decision made after evaluating the current GameState
    and candidate ProposedActions.
    """

    decision_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this decision instance for auditability.",
    )
    selected_action: ProposedAction = Field(
        ...,
        description="The winning action chosen by Laya to be executed.",
    )
    confidence_score: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Estimated confidence in the decision (0.0 to 1.0).",
    )
    rationale: str = Field(
        default="Optimal action selected by Laya strategy engine.",
        description="Detailed strategic justification explaining why this action was selected.",
    )
    alternatives_considered: List[ProposedAction] = Field(
        default_factory=list,
        description="Candidate actions that were considered and evaluated before selection.",
    )
    timestamp: datetime = Field(
        default_factory=_utc_now,
        description="UTC timestamp when the decision was finalized.",
    )


class ActionSubmissionResult(BaseModel):
    """Result of submitting an action to the game server.

    Standardizes the outcome of an action submission regardless of whether
    the underlying transport is HTTP REST, WebSocket, or an official SDK.
    """

    success: bool = Field(
        ...,
        description="True if the action was accepted by the game server/engine; False otherwise.",
    )
    action_id: Optional[str] = Field(
        default=None,
        description="Identifier of the submitted action, if tracked or returned by server.",
    )
    response_code: Optional[int] = Field(
        default=None,
        description="HTTP status code or protocol-level response code (e.g. 200, 400).",
    )
    message: Optional[str] = Field(
        default=None,
        description="Human-readable status or diagnostic error message from the game engine.",
    )
    latency_ms: Optional[float] = Field(
        default=None,
        ge=0.0,
        description="Roundtrip network latency in milliseconds for the submission call.",
    )
    raw_response: Dict[str, Any] = Field(
        default_factory=dict,
        description="Preserved raw server response payload for audit and debugging.",
    )
    timestamp: datetime = Field(
        default_factory=_utc_now,
        description="UTC timestamp when the submission result was processed.",
    )
